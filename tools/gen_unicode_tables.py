"""Generates the Unicode general-category range tables our tokenizer needs (\\p{L}, \\p{N}, \\p{M}) as a Rust source file, from Python's unicodedata (an offline fact table, not a model).

    python tools/gen_unicode_tables.py > crates/forge-tok/src/unicode_tables.rs

The byte-level BPE pre-tokenizers of the GPT-2 / Llama-3 / Qwen families are regular expressions over Unicode letters, numbers and spaces; Rust's standard library has no general-category
lookup (`char::is_alphabetic` is the Alphabetic property, which also contains marks), so we carry the ranges ourselves. The Unicode version of the source is written into the file header.
"""
import sys
import unicodedata


def ranges(pred):
    out, start, prev = [], None, None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(unicodedata.category(chr(cp)))
        if ok:
            if start is None:
                start = cp
            prev = cp
        elif start is not None:
            out.append((start, prev))
            start = None
    if start is not None:
        out.append((start, prev))
    return out


def emit(name, doc, rs):
    print(f"/// {doc} ({len(rs)} ranges)")
    print(f"pub static {name}: [(u32, u32); {len(rs)}] = [")
    line = "   "
    for a, b in rs:
        item = f" (0x{a:X}, 0x{b:X}),"
        if len(line) + len(item) > 150:
            print(line)
            line = "   "
        line += item
    print(line)
    print("];")
    print()


def main() -> int:
    print(f"// @generated by tools/gen_unicode_tables.py from Python {sys.version.split()[0]} unicodedata (Unicode {unicodedata.unidata_version}). Do not edit.")
    print()
    emit("LETTER", "Unicode general category L (Lu, Ll, Lt, Lm, Lo)", ranges(lambda c: c[0] == "L"))
    emit("NUMBER", "Unicode general category N (Nd, Nl, No)", ranges(lambda c: c[0] == "N"))
    emit("MARK", "Unicode general category M (Mn, Mc, Me)", ranges(lambda c: c[0] == "M"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
