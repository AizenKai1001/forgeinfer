"""gen_unicode_punct.py: crates/forge-tok/src/unicode_punct.rs, the ranges of the Unicode categories that BERT's basic tokenizer needs: punctuation (P: Pc Pd Ps Pe Pi Pf Po), the nonspacing marks (Mn,
the accents it strips after NFD) and the other-category controls and format characters (C: Cc Cf Cs Co Cn, which it drops).
Run with the same Python that generated the other tables (Unicode 15.1: Python 3.12 and 3.13), `python tools/gen_unicode_punct.py`."""
import sys
import unicodedata

print("Unicode", unicodedata.unidata_version, file=sys.stderr)


def ranges_of(pred):
    out = []
    start = prev = None
    for cp in range(0x110000):
        if pred(unicodedata.category(chr(cp))):
            if start is None:
                start = prev = cp
            elif cp == prev + 1:
                prev = cp
            else:
                out.append((start, prev))
                start = prev = cp
    if start is not None:
        out.append((start, prev))
    return out


tables = [
    ("PUNCT", "punctuation categories P*", ranges_of(lambda c: c.startswith("P"))),
    ("MN", "nonspacing marks Mn", ranges_of(lambda c: c == "Mn")),
    # surrogates, private use and unassigned code points are in C too; BERT drops them like the controls
    ("OTHER", "other categories C* (controls, format characters, surrogates, private use, unassigned)", ranges_of(lambda c: c.startswith("C"))),
]
out = ["// @generated by tools/gen_unicode_punct.py (Unicode " + unicodedata.unidata_version + "). Do not edit."]
for name, doc, rs in tables:
    out.append("")
    out.append(f"/// {doc} ({len(rs)} ranges)")
    out.append(f"pub static {name}: [(u32, u32); {len(rs)}] = [")
    for lo, hi in rs:
        out.append(f"    (0x{lo:X}, 0x{hi:X}),")
    out.append("];")
    print(name, len(rs), "ranges", file=sys.stderr)
path = "crates/forge-tok/src/unicode_punct.rs"
open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
