"""Generates the Unicode normalization (NFC) data our tokenizer needs as a Rust source file, from Python's unicodedata (an offline fact table, not a model).

    python tools/gen_unicode_norm.py > crates/forge-tok/src/unicode_norm_tables.rs

Qwen's tokenizer.json declares an NFC normalizer, so the text must be put in canonical composed form before byte-level BPE. NFC = canonical decomposition, canonical reordering of combining marks
by combining class, canonical composition. Hangul syllables are handled by the algorithm in Rust (constants only here). We emit:
  CCC       sorted (start, end, class) ranges of code points with a non-zero canonical combining class
  DECOMP    sorted (code point, [fully decomposed canonical sequence]) for every code point with a canonical decomposition (compatibility mappings are NOT included: NFC does not use them)
  COMPOSE   sorted (first, second, composite) primary composites: pairs that NFC really combines (composition exclusions are excluded by testing unicodedata.normalize itself)
"""
import sys
import unicodedata


def canonical_decomposition(cp):
    """Full canonical decomposition of one code point as a list of code points (empty list = none)."""
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith("<"):                       # compatibility mapping: not canonical
        return []
    out = []
    for h in d.split():
        sub = int(h, 16)
        again = canonical_decomposition(sub)
        out.extend(again if again else [sub])
    return out


def main() -> int:
    ccc = []
    start = prev = cls = None
    for cp in range(0x110000):
        c = unicodedata.combining(chr(cp)) if not (0xD800 <= cp <= 0xDFFF) else 0
        if c and c == cls and cp == prev + 1:
            prev = cp
            continue
        if cls:
            ccc.append((start, prev, cls))
            cls = None
        if c:
            start, prev, cls = cp, cp, c
    if cls:
        ccc.append((start, prev, cls))

    decomp = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF or 0xAC00 <= cp <= 0xD7A3:          # Hangul syllables are algorithmic
            continue
        d = canonical_decomposition(cp)
        if d:
            decomp.append((cp, d))

    compose = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF or 0xAC00 <= cp <= 0xD7A3:
            continue
        raw = unicodedata.decomposition(chr(cp))
        if not raw or raw.startswith("<"):
            continue
        parts = [int(h, 16) for h in raw.split()]
        if len(parts) != 2:
            continue
        if unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(cp):
            compose.append((parts[1] if False else parts[0], parts[1], cp))
    compose.sort()

    print(f"// @generated by tools/gen_unicode_norm.py from Python {sys.version.split()[0]} unicodedata (Unicode {unicodedata.unidata_version}). Do not edit.")
    print()
    print(f"/// Canonical combining classes: (first code point, last code point, class) ({len(ccc)} ranges)")
    print(f"pub static CCC: [(u32, u32, u8); {len(ccc)}] = [")
    line = "   "
    for a, b, c in ccc:
        item = f" (0x{a:X}, 0x{b:X}, {c}),"
        if len(line) + len(item) > 150:
            print(line)
            line = "   "
        line += item
    print(line)
    print("];")
    print()
    flat = []
    index = []
    for cp, d in decomp:
        index.append((cp, len(flat), len(d)))
        flat.extend(d)
    print(f"/// Canonical full decompositions: (code point, offset into DECOMP_DATA, length) ({len(index)} entries)")
    print(f"pub static DECOMP_INDEX: [(u32, u32, u8); {len(index)}] = [")
    line = "   "
    for cp, off, ln in index:
        item = f" (0x{cp:X}, {off}, {ln}),"
        if len(line) + len(item) > 150:
            print(line)
            line = "   "
        line += item
    print(line)
    print("];")
    print()
    print(f"pub static DECOMP_DATA: [u32; {len(flat)}] = [")
    line = "   "
    for v in flat:
        item = f" 0x{v:X},"
        if len(line) + len(item) > 150:
            print(line)
            line = "   "
        line += item
    print(line)
    print("];")
    print()
    print(f"/// Primary composites: (first, second, composite), sorted by (first, second) ({len(compose)} entries)")
    print(f"pub static COMPOSE: [(u32, u32, u32); {len(compose)}] = [")
    line = "   "
    for a, b, c in compose:
        item = f" (0x{a:X}, 0x{b:X}, 0x{c:X}),"
        if len(line) + len(item) > 150:
            print(line)
            line = "   "
        line += item
    print(line)
    print("];")
    return 0


if __name__ == "__main__":
    sys.exit(main())
